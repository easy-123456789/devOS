uint8_t font_row(char ch, unsigned row)
{
    if (row == 0 || row == 7) return 0;
    unsigned r = row - 1;
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 'a' + 'A');
    if (ch >= 'A' && ch <= 'Z') return (uint8_t)(alpha[ch - 'A'][r] << 1);
    if (ch >= '0' && ch <= '9') return (uint8_t)(digits[ch - '0'][r] << 1);
    switch (ch) {
    case '.': return row == 6 ? 8 : 0;
    case ',': return row == 6 ? 8 : (row == 7 ? 16 : 0);
    case ':': return (row == 3 || row == 6) ? 8 : 0;
    case '[': return (uint8_t)((row == 1 || row == 6) ? 30 : 16);
    case ']': return (uint8_t)((row == 1 || row == 6) ? 30 : 2);
    case '+': return row == 4 ? 28 : (row == 3 || row == 5 ? 8 : 0);
    case '-': return row == 4 ? 28 : 0;
    case '|': return 8;
    case '/': return (uint8_t)(1u << (row - 1));
    case '=': return (row == 3 || row == 5) ? 28 : 0;
    default: return 0;
    }
}
